#pragma once
#include <Arduino.h>


// ─── Пины ESP32-C3 SuperMini ───────────────────────────────────────────────
// Из глубокого сна C3 будят только GPIO0–5, поэтому кнопка энкодера — на GPIO1.
// GPIO2, 8, 9 — пины загрузки, GPIO8 — синий светодиод платы: их не занимаем.
#define PIN_ENC_A     3      // энкодер CLK
#define PIN_ENC_B     4      // энкодер DT
#define PIN_ENC_SW    1      // кнопка энкодера → GND (+ внешняя подтяжка 10к к 3V3)
#define PIN_OLED_SDA  6
#define PIN_OLED_SCL  7
#define PIN_BAT_ADC   0      // делитель 100к/100к от «+» аккумулятора
#define PIN_BTN_STOP  5      // кнопка СТОП на панели → GND (+ внешняя подтяжка 10к к 3V3), будит из сна

// ─── Энкодер ───────────────────────────────────────────────────────────────
#define ENC_STEPS_PER_DETENT  4    // EC11/KY-040: 4 перехода на щелчок (у некоторых 2)
#define ENC_REVERSE           0    // 1 — если крутится «не в ту сторону»
#define BTN_DEBOUNCE_MS       20
#define LONG_PRESS_MS         700  // удержание энкодера — «назад» без сохранения
#define PARK_HOLD_MS          1500 // удержание СТОП — парковка (в шапке идёт полоса)
#define PARK_HOLD_SHOW_MS     150  // короче — обычное нажатие, полосу не рисуем
// Защитное окно: клик и поворот не исполняются (целились в то, чего на экране уже нет).
// Пока окно идёт, курсор рисуется рамкой, а не заливкой.
#define SCREEN_GUARD_MS       400  // дозатор сменил состояние
#define MOVE_END_GUARD_MS     1500 // мотор только что встал (после парковки/зарядки/дозы/калибровки):
                                   // курсор переехал на «СТАРТ…», повторный «СТОП» не должен его нажать
#define WAKE_GUARD_MS         500  // экран проснулся — остаток того же поворота не двигает курсор/каретку
#define LINK_GUARD_MS         800  // связь вернулась
#define CONFIRM_GUARD_MS      300  // открылся диалог подтверждения
#define OTA_HOLD_MS           10000 // энкодер + СТОП вместе — режим обновления прошивки
#define OTA_HOLD_SHOW_MS      1000  // с этого момента в шапке полоса «ОБНОВЛЕНИЕ»
#define RESET_HOLD_MS         5000  // ручка зажата с самого включения столько — сброс настроек пульта
#define RESET_HOLD_SHOW_MS    1000  //   (на случай, когда экран не видно: яркость, сон); полоса с этого момента
#define STOP_PENDING_MS       4000 // СТОП нажат до появления связи — отправить, если связь появится за это время

// ─── Связь ─────────────────────────────────────────────────────────────────
#define HELLO_PERIOD_MS       300  // пока экран не спит — «я тут», дозатор шлёт STATE
#define LINK_LOST_MS          1500 // нет STATE дольше — «НЕТ СВЯЗИ»
#define ACK_RETRY_MS          200  // нет ACK — повторять каждые столько (дозатор отбросит дубль по seq)
#define ACK_FAIL_MS           900  // нет ACK и после повторов — «НЕТ ОТВЕТА»
#define ACK_FAIL_URGENT_MS    3000 // СТОП и парковку повторяем дольше
#define CMD_QUEUE_LEN         8    // команд ждут своей очереди, пока одна в полёте
#define REMOTE_TX_POWER       WIFI_POWER_8_5dBm   // у SuperMini на полной мощности связь хуже

// ─── Питание ───────────────────────────────────────────────────────────────
#define BAT_DIVIDER           2.0f   // (R1+R2)/R2
#define BAT_EMPTY_V           3.35f  // ниже — пульт сам уходит в сон (защита банки и стабилизатора)
#define BAT_NONE_V            2.5f   // ниже — считаем, что питаемся от USB без банки
#define BAT_MAX_V             4.4f   // выше банка не бывает: делитель не припаян (вход висит) — тоже USB
#define SCREEN_SLEEP_DEFAULT_S 30
#define NO_LINK_SLEEP_MS      120000  // 2 мин без дозатора (и без нажатий) — глубокий сон
#define BRIGHT_DEFAULT        6       // яркость экрана 1..10, 1 — для работы в темноте

// ─── Обновление прошивки (энкодер + СТОП 10 с) ────────────────────────────────
#define OTA_TX_POWER          WIFI_POWER_5dBm     // телефон рядом; меньше ток передачи — меньше просадка питания
#define OTA_SSID              "dozator-ota"
#define OTA_PASS              "dozator123"
#define OTA_IDLE_MS           600000  // 10 мин без загрузки — выход в обычный режим
#define OTA_MIN_BATTERY_PCT   20      // ниже — не начинаем: отключение посреди записи

// ─── Экран ─────────────────────────────────────────────────────────────────
#define UI_FRAME_MS           33     // ~30 кадров/с
#define TOAST_SHORT_MS        800    // «СОХРАНЕНО», «СТОП», «ПАРКОВКА»
#define TOAST_LONG_MS         1500   // отказы и предупреждения
#define EMPTY_SLEEP_DELAY_MS  3000   // банка села: столько показываем «ЗАРЯДИ АККУМУЛЯТОР», потом сон
